-- Run with a Lua 5.1 interpreter built from the generated llex-xray.c.
local function evaluates(source, expected)
    local chunk, err = loadstring(source)
    assert(chunk, err)
    assert(chunk() == expected)
end
evaluates('return 12 / 3', 4)
evaluates('return 12 /* comment */ / 3 // trailing comment', 4)
evaluates('/* block with **/ return 7', 7)
evaluates('// first line\r\n/* block\nline */ return 9', 9)
evaluates('return "http://example.test/*literal*/"', 'http://example.test/*literal*/')
evaluates('return [[// /*literal*/]]', '// /*literal*/')
evaluates('-- normal Lua comment\nreturn 3', 3)
evaluates('--[=[ /* // ]=]\nreturn 4', 4)
local chunk, err = loadstring('/* unfinished')
assert(not chunk and err:find('unfinished C%-style comment'))
chunk, err = loadstring('/* first\nsecond\n*/\nreturn )')
assert(not chunk and err:find(':4:'), err)
print('X-Ray Lua comment compatibility: passed')
